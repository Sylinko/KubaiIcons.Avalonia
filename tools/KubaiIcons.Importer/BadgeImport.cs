using System.Globalization;
using System.Text;
using System.Text.Json;
using Avalonia.Media;
using KubaiIcons.Avalonia.Rendering;

namespace KubaiIcons.Importer;

internal static class BadgeImport
{
    public static void Add(string root, JsonElement data, Dictionary<string, byte[]> files, SortedDictionary<string, string> labels)
    {
        const string directory = "src/KubaiIcons.Avalonia/Art/Badges";
        var blocks = new Dictionary<string, byte[]>(StringComparer.Ordinal);
        foreach (var item in data.GetProperty("badges").EnumerateObject())
        {
            blocks.Add($"{directory}/{item.Name}.kbi", ArtWriter.Block(ArtKind.Badge, w => Write(w, item.Value)));
        }

        ImportOutput.CheckInventory(root, directory, blocks.Keys);
        foreach (var block in blocks)
        {
            files.Add(block.Key, block.Value);
        }

        var entries = data.GetProperty("entries");
        var members = entries.EnumerateArray()
            .Select(entry => entry.GetProperty("name").GetString()!)
            .Order(StringComparer.Ordinal);
        files.Add("catalog/layered-compositions.json", Encoding.UTF8.GetBytes(CatalogJson.WriteNames(members)));

        var code = new StringBuilder(
            "// <auto-generated/>\n" +
            "namespace KubaiIcons.Avalonia.Rendering;\n\n" +
            "internal static class CompositionData\n{\n" +
            "    public static BadgePlacement? Get(KubaiIconKind kind) => kind switch\n    {\n");

        foreach (var entry in entries.EnumerateArray().OrderBy(item => item.GetProperty("name").GetString(), StringComparer.Ordinal))
        {
            AppendPlacement(code, labels, entry);
        }

        var activeBases = data.GetProperty("activeBases")
            .EnumerateArray()
            .Select(e => e.GetString()!)
            .ToHashSet(StringComparer.Ordinal);
        var active = entries
            .EnumerateArray()
            .Where(e => !e.TryGetProperty("overlay", out _) && activeBases.Contains(e.GetProperty("base").GetString()!))
            .Select(e => e.GetProperty("name").GetString()!)
            .Concat(activeBases)
            .Order(StringComparer.Ordinal);
        code.Append("        _ => null\n    };\n\n    private static readonly HashSet<KubaiIconKind> Active =\n    [\n");
        foreach (var slug in active)
        {
            code.Append("        KubaiIconKind.").Append(CatalogImport.EnumName(slug)).Append(",\n");
        }

        code.Append("    ];\n\n    public static bool SupportsActive(KubaiIconKind kind) => Active.Contains(kind);\n}\n");
        files.Add("src/KubaiIcons.Avalonia/Rendering/CompositionData.g.cs", Encoding.UTF8.GetBytes(code.ToString()));
    }

    private static void AppendPlacement(StringBuilder code, SortedDictionary<string, string> labels, JsonElement entry)
    {
        var name = entry.GetProperty("name").GetString()!;
        var kind = CatalogImport.EnumName(name);
        var baseKind = CatalogImport.EnumName(entry.GetProperty("base").GetString()!);
        var badge = entry.GetProperty("badge").GetString();
        var x = entry.GetProperty("x").GetDouble();
        var y = entry.GetProperty("y").GetDouble();
        var overlayArgument = entry.TryGetProperty("overlay", out _) ? ", true" : "";

        labels.Add(name, entry.GetProperty("label").GetString()!);
        code.Append(CultureInfo.InvariantCulture, $"        KubaiIconKind.{kind} => new(KubaiIconKind.{baseKind}, ");
        code.Append(CultureInfo.InvariantCulture, $"\"{badge}\", {x:R}, {y:R}{overlayArgument}),\n");
    }

    private static void Write(BinaryWriter w, JsonElement art)
    {
        w.Write(Color.Parse(art.GetProperty("tone").GetString()!).ToUInt32());
        var tracks = art.GetProperty("tracks");
        w.Write7BitEncodedInt(tracks.GetArrayLength());
        foreach (var track in tracks.EnumerateArray())
        {
            foreach (var curve in track.EnumerateArray())
            {
                w.Write7BitEncodedInt(curve.GetArrayLength());
                foreach (var key in curve.EnumerateArray())
                {
                    w.Write(key[0].GetDouble());
                    w.Write(key[1].GetDouble());
                }
            }
        }

        var shapes = art.GetProperty("shapes").EnumerateArray().ToArray();
        var paths = shapes.Where(s => s.TryGetProperty("path", out _))
            .Select(s => PathCompiler.Compile(
                s.GetProperty("path").GetString()!,
                s.GetProperty("even").GetBoolean() ? FillRule.EvenOdd : FillRule.NonZero))
            .ToArray();
        ArtWriter.Paths(w, paths);
        var path = 0;
        w.Write7BitEncodedInt(shapes.Length);
        foreach (var s in shapes)
        {
            var transforms = s.GetProperty("transforms");
            w.Write7BitEncodedInt(transforms.GetArrayLength());
            foreach (var t in transforms.EnumerateArray())
            {
                var op = t[0].GetString() switch
                {
                    "translate" => 0,
                    "scale" => 1,
                    "rotate" => 2,
                    _ => throw new InvalidDataException("Unknown transform.")
                };
                w.Write((byte)op);
                ArtWriter.Index(w, t[1].GetInt32());
                ArtWriter.Index(w, t.GetArrayLength() == 3 ? t[2].GetInt32() : -1);
            }

            w.Write(s.GetProperty("width").GetDouble());
            w.Write(
                (byte)((s.GetProperty("disc").GetBoolean() ? 1 : 0) | (s.GetProperty("round").GetBoolean() ? 2 : 0) |
                    (s.GetProperty("join").GetBoolean() ? 4 : 0)));
            w.Write(s.TryGetProperty("dash", out var dash) ? dash.GetDouble() : 0d);
            ArtWriter.Index(w, s.TryGetProperty("offset", out var offset) ? offset.GetInt32() : -1);
            if (s.TryGetProperty("circle", out var circle))
            {
                w.Write((byte)0);
                foreach (var n in circle.EnumerateArray())
                {
                    w.Write(n.GetDouble());
                }
            }
            else if (s.TryGetProperty("line", out var line))
            {
                w.Write((byte)1);
                foreach (var n in line.EnumerateArray())
                {
                    ArtWriter.Index(w, n.GetInt32());
                }
            }
            else
            {
                w.Write((byte)2);
                ArtWriter.Index(w, path++);
            }
        }
    }
}